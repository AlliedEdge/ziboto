package com.ziboto.backend.preview.enums;

/**
 * Enum for preview types.
 * 
 * @author Ziboto Team
 * @since V3
 */
public enum PreviewType {
    THUMBNAIL,    // Small thumbnail image
    IMAGE,        // Full image preview
    PDF,          // PDF preview/conversion
    VIDEO,        // Video preview/thumbnail
    AUDIO,        // Audio waveform/metadata
    DOCUMENT,     // Document preview (Word, Excel, etc.)
    CODE          // Code syntax highlighting
}
